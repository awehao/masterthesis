#!/usr/bin/env python3
"""手臂關節庫倫摩擦的有界前饋（Codex 20261115 第五趟後裁定）。
模擬模型（門任務版）每個手臂關節有 τ_f＝1.0 N·m 的靜／動摩擦；位置驅動 kp 下，運動中關節落後設定點 δ＝τ_f/kp（方向＝運動方向）。
前饋：設定點加 ff(q̇_ref)＝δ·sat(q̇_ref／V0)，q̇_ref＝閉鏈（或抓持 IK）關節參考速度——不是設定點命令速度。
  sat 為分段線性飽和 ⇒ 過零連續、|ff|≤δ（有界）、參考速度為零時 ff＝0（停止時自動收回）。
前饋量算進設定點目標，所以經由手臂命令 u＝(S_目標−s_預測)/DT 進入管線：命令的速率／加速度驗收、在途管線、停止預測都看得到它，不是送出端另加的偏移。
控制器內部的受控對象模型仍是無摩擦一階模型（預測的設定點含前饋、預測的關節不含摩擦落後）⇒ 預測與實際相差至多 δ 量級，不宣稱已消除。
不重複補償：起點靜態偏置（off_static／q−s）可能已含 ≤δ 的黏滯殘差，方向未知，本前饋不嘗試扣除（照實列為殘差來源）。"""
import numpy as np

V0 = 0.02                                                            # rad/s：飽和速度（分段線性過零寬度）


def ff(qd_ref, tau_f, kp):
    if not tau_f:
        return 0.0
    return (float(tau_f) / float(kp)) * np.clip(np.asarray(qd_ref, float) / V0, -1.0, 1.0)
