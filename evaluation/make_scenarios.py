"""Generate the scenario suite, placing obstacles ON the route the robot drives.

Placement is computed from a recorded baseline trajectory rather than chosen by
hand, because hand-placed obstacles are easy to get wrong in a way that looks
fine: in the existing scenario two of the four movers are never met at all (the
route passes 3.8 m and 1.7 m away), so every "dynamic avoidance" number so far
rests on about two encounters per run, one of which dominates.

Each scenario isolates one failure mode that has actually been observed or that
the current design predicts but has never exercised:

  corridor  the mover sweeps ALONG the route -- the pathological case, where
            there is nothing to go around and the robot can only follow or
            retreat (43.5 s, 26% of a run, 4x the backing, 65% of reversals)
  crossing  a clean perpendicular crossing: the case constant-velocity
            prediction is actually valid for, and which has never been isolated
  fast      the same geometry at 0.40 m/s, where the 2.0 m trigger range leaves
            about 5 s of warning
  converge  two movers arriving at one point from opposite sides -- the
            multi-obstacle path, exercised in 0.09% of frames so far, i.e.
            never
  oneway    long one-way traversals approximating pedestrians. 43% of reversals
            land within 3 s of a mover turning around; a mover that never turns
            around should not produce them, and if that holds, most of the
            reversal problem is an artefact of ping-pong scenery
  overtake  a slower mover going the SAME way: _blocking requires fx > 0, so
            this is the geometry the detour was never designed for
  parked    a mover with speed 0 -- tests the static/dynamic classification
            directly, which is what let a pillar go unowned
  pinch     a mover beside a narrow passage, so neither side has room: the
            "do not commit" branch, never exercised

    python3 evaluation/make_scenarios.py && python3 evaluation/check_scenario.py corridor crossing ...
"""
import math
import os

import numpy as np

from check_scenario import (nominal_path, wall_dist, PILLARS, R_OBS,
                            CBF_MARGIN, R_ROBOT, SHARE)

NEED = R_OBS + CBF_MARGIN + R_ROBOT          # 0.93 m to get past a mover


def route_points(path, s_from, s_to):
    """Points on the route between two arclength fractions, with tangents."""
    seg = np.linalg.norm(np.diff(path, axis=0), axis=1)
    s = np.concatenate([[0], np.cumsum(seg)])
    total = s[-1]
    out = []
    for i in range(1, len(path) - 1):
        if s_from * total <= s[i] <= s_to * total:
            t = path[i + 1] - path[i - 1]
            n = np.linalg.norm(t)
            if n > 1e-6:
                out.append((path[i], t / n))
    return out


def best_spot(path, s_from, s_to, want_room):
    """The point in that stretch of route with the most space around it."""
    best, best_r = None, -1.0
    for p, tan in route_points(path, s_from, s_to):
        if min(math.hypot(p[0] - px, p[1] - py) for px, py in PILLARS) < 1.2:
            continue
        r = wall_dist(*p)
        if r > best_r:
            best, best_r = (p, tan), r
    return best if best_r >= want_room else None


def free_len(p, d, limit):
    """How far one can go from p along d before clearance drops below R_OBS."""
    t = 0.0
    while t < limit:
        q = p + d * (t + 0.1)
        if wall_dist(*q) < R_OBS + 0.10:
            break
        if min(math.hypot(q[0] - px, q[1] - py) for px, py in PILLARS) < R_OBS + 0.35:
            break
        t += 0.1
    return t


def ob(name, a, b, speed, radius=0.25):
    return (f'  - name:   {name}\n'
            f'    start:  [{a[0]:.2f}, {a[1]:.2f}]\n'
            f'    end:    [{b[0]:.2f}, {b[1]:.2f}]\n'
            f'    speed:  {speed}\n'
            f'    radius: {radius}\n'
            f'    height: 1.0\n')


def write(name, body, note):
    f = f'{SHARE}/config/dynamic_trajectories_{name}.yaml'
    with open(f, 'w') as fh:
        fh.write(f'# {note}\n#\n# Generated by evaluation/make_scenarios.py from a recorded\n'
                 f'# baseline route, so the obstacles are actually MET. Validate with\n'
                 f'#   python3 evaluation/check_scenario.py {name}\n\n'
                 f'dynamic_obstacles:\n\n{body}')
    print(f'  wrote {os.path.basename(f)}')


def main():
    path = nominal_path()
    if path is None:
        print('no baseline bag to take the route from'); return 1

    def cross_at(frac_lo, frac_hi, speed, name, half=None):
        spot = best_spot(path, frac_lo, frac_hi, NEED)
        if spot is None:
            return None
        p, tan = spot
        nrm = np.array([-tan[1], tan[0]])
        h = half or min(free_len(p, nrm, 4.0), free_len(p, -nrm, 4.0))
        if h < 0.8:
            return None
        return ob(name, p + nrm * h, p - nrm * h, speed)

    print('generating scenarios:')

    # crossing: perpendicular, robot-comparable speed
    a = cross_at(0.35, 0.65, 0.22, 'dyn_obs_2')
    write('crossing', a or '', 'Perpendicular crossing at robot speed -- the case '
          'constant-velocity prediction is valid for.')

    # fast: same geometry, 0.40 m/s
    b = cross_at(0.35, 0.65, 0.40, 'dyn_obs_2')
    write('fast', b or '', 'Perpendicular crossing at 0.40 m/s: the 2.0 m detour '
          'trigger leaves ~5 s of warning.')

    # converge: two crossings close together from opposite ends
    c1 = cross_at(0.30, 0.45, 0.25, 'dyn_obs_2')
    c2 = cross_at(0.50, 0.65, 0.25, 'dyn_obs_5')
    write('converge', (c1 or '') + (c2 or ''),
          'Two movers meeting the robot in quick succession -- the multi-obstacle '
          'path, exercised in 0.09% of frames so far.')

    # oneway: long traversals, so a turnaround is unlikely during the encounter
    spot = best_spot(path, 0.30, 0.60, NEED)
    body = ''
    if spot is not None:
        p, tan = spot
        nrm = np.array([-tan[1], tan[0]])
        h = min(free_len(p, nrm, 8.0), free_len(p, -nrm, 8.0))
        if h >= 1.5:
            body = ob('dyn_obs_2', p + nrm * h, p - nrm * h, 0.30)
    write('oneway', body, 'Long one-way traversal (period >> encounter), '
          'approximating a pedestrian rather than a ping-pong prop.')

    # overtake: same direction as the robot, slower
    spot = best_spot(path, 0.30, 0.55, NEED)
    body = ''
    if spot is not None:
        p, tan = spot
        h = min(free_len(p, tan, 5.0), free_len(p, -tan, 5.0))
        if h >= 1.0:
            body = ob('dyn_obs_2', p - tan * h, p + tan * h, 0.12)
    write('overtake', body, 'A slower mover going the SAME way: _blocking needs '
          'fx > 0, so this is the geometry the detour never targeted.')

    # parked: speed 0, on the route
    spot = best_spot(path, 0.35, 0.60, NEED)
    body = ob('dyn_obs_2', spot[0], spot[0], 0.0) if spot else ''
    write('parked', body, 'A stationary "dynamic" obstacle: tests the '
          'static/dynamic split that left a pillar unowned.')

    # pinch: put the mover where the corridor is narrow, so neither side clears
    best, best_r = None, 9.9
    for p, tan in route_points(path, 0.15, 0.85):
        r = wall_dist(*p)
        if 0.45 < r < best_r:
            best, best_r = (p, tan), r
    body = ''
    if best is not None:
        p, tan = best
        # ALONG the corridor, not across it: a narrow passage has no room for a
        # perpendicular segment, and driving the mover into the wall was exactly
        # the failure the existing config records ("end sat INSIDE a wall ->
        # obstacle drove in, got stuck and froze").
        h = min(free_len(p, tan, 3.0), free_len(p, -tan, 3.0))
        if h >= 0.5:
            body = ob('dyn_obs_2', p + tan * h, p - tan * h, 0.20)
            print(f'    pinch at clearance {best_r:.2f} m '
                  f'(needs {NEED:.2f} to pass), segment {2*h:.1f} m along it')
    write('pinch', body, 'Mover in a passage too narrow to go around: the '
          '"do not commit, yield instead" branch.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
