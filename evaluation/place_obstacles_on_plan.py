"""Sample the latest /plan and place 6 static obstacles along it.

Workflow:
    1) Bring up Gazebo + Nav2 (any stack, just so /plan gets published):
           ros2 launch ammr_bringup gazebo_dynamic.launch.py dynamic:=false
           ros2 launch ammr_wholebody_mpc gmpc_nav2.launch.py
    2) Send a goal:
           ros2 topic pub /goal_pose geometry_msgs/msg/PoseStamped \
             "{header: {frame_id: 'map'}, pose: {position: {x: 17.0, y: 17.0}, \
                                                 orientation: {w: 1.0}}}" --once
    3) Wait for /plan to appear in your Foxglove / log, then run this script:
           python3 evaluation/place_obstacles_on_plan.py
    4) Tear down + rebuild + restart Gazebo so the new spawn poses take effect:
           pkill -9 -f 'gz sim'; pkill -9 -f gazebo
           colcon build --packages-select ammr_bringup
           source install/setup.bash
           ros2 launch ammr_bringup gazebo_dynamic.launch.py dynamic:=false
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import numpy as np

import rclpy
from rclpy.node import Node
from rclpy.qos import QoSProfile, QoSReliabilityPolicy, QoSHistoryPolicy

from nav_msgs.msg import Path as NavPath


ROOT       = Path(__file__).resolve().parent.parent
YAML_PATH  = ROOT / 'src/ammr_bringup/config/dynamic_trajectories.yaml'
SDF_PATH   = ROOT / 'src/ammr_bringup/worlds/random_room_dynamic.sdf'

N_OBSTACLES = 6
SAMPLE_FRACTIONS = [0.12, 0.27, 0.42, 0.55, 0.70, 0.85]   # arclength fractions
SWEEP_DELTA_Y    = 1.5                                    # cosmetic end[y] - start[y]
RADIUS           = 0.25
HEIGHT           = 1.0
SPEED            = 0.4
NAMES            = ['dyn_obs_1', 'dyn_obs_2', 'dyn_obs_3',
                    'dyn_obs_4', 'dyn_obs_5', 'dyn_obs_0']


# ---------------------------------------------------------------------------
# Plan capture
# ---------------------------------------------------------------------------

class PlanCatcher(Node):
    def __init__(self):
        super().__init__('plan_sampler')
        self.plan = None
        qos = QoSProfile(reliability=QoSReliabilityPolicy.RELIABLE,
                         history=QoSHistoryPolicy.KEEP_LAST, depth=1)
        self.sub = self.create_subscription(NavPath, '/plan',
                                            self._cb, qos)

    def _cb(self, msg: NavPath):
        if len(msg.poses) >= 2:
            self.plan = msg


def wait_for_plan(timeout_s: float = 20.0) -> NavPath:
    rclpy.init()
    n = PlanCatcher()
    t0 = n.get_clock().now().nanoseconds * 1e-9
    while rclpy.ok():
        rclpy.spin_once(n, timeout_sec=0.1)
        if n.plan is not None:
            break
        if n.get_clock().now().nanoseconds * 1e-9 - t0 > timeout_s:
            n.destroy_node()
            rclpy.shutdown()
            raise SystemExit('Timed out waiting for /plan. Did you send a goal?')
    plan = n.plan
    n.destroy_node()
    rclpy.shutdown()
    return plan


def sample_points(plan: NavPath) -> list[tuple[float, float]]:
    xy = np.array([[p.pose.position.x, p.pose.position.y] for p in plan.poses])
    seg = np.linalg.norm(np.diff(xy, axis=0), axis=1)
    s   = np.concatenate([[0.0], np.cumsum(seg)])
    total = s[-1]
    pts = []
    for f in SAMPLE_FRACTIONS:
        target = f * total
        idx = int(np.searchsorted(s, target))
        idx = max(0, min(idx, len(xy) - 1))
        pts.append((float(xy[idx, 0]), float(xy[idx, 1])))
    return pts


# ---------------------------------------------------------------------------
# File writers
# ---------------------------------------------------------------------------

YAML_TEMPLATE = """# Static obstacles placed along the SmacPlanner /plan from (0,0) -> (17,17).
# Generated by evaluation/place_obstacles_on_plan.py
# Launch with `dynamic:=false` to keep them at the spawn pose.

dynamic_obstacles:

{entries}"""

YAML_ENTRY = """  - name:   {name}
    start:  [{x:.3f}, {y:.3f}]
    end:    [{x:.3f}, {ye:.3f}]
    speed:  {speed:.2f}
    radius: {radius:.3f}
    height: {height:.3f}
"""


def write_yaml(positions: list[tuple[float, float]]):
    entries = []
    for name, (x, y) in zip(NAMES, positions):
        entries.append(YAML_ENTRY.format(
            name=name, x=x, y=y, ye=y + SWEEP_DELTA_Y,
            speed=SPEED, radius=RADIUS, height=HEIGHT,
        ))
    YAML_PATH.write_text(YAML_TEMPLATE.format(entries='\n'.join(entries)))
    print(f'  wrote {YAML_PATH}')


def write_sdf(positions: list[tuple[float, float]]):
    """Edit each <model name="dyn_obs_X"> <pose>... in place."""
    text = SDF_PATH.read_text()
    name_to_pos = dict(zip(NAMES, positions))
    for name, (x, y) in name_to_pos.items():
        # find  <model name="<name>">\n      <pose>... </pose>
        pat = re.compile(
            rf'(<model name="{re.escape(name)}">\s*\n\s*<pose>)'
            r'[^<]*'
            r'(</pose>)'
        )
        new_pose = f'{x:.4f} {y:.4f} 0.5000 0 0 0'
        text, n = pat.subn(rf'\g<1>{new_pose}\g<2>', text, count=1)
        if n != 1:
            print(f'  WARN: could not patch {name} in SDF (found {n} matches)')
    SDF_PATH.write_text(text)
    print(f'  wrote {SDF_PATH}')


# ---------------------------------------------------------------------------
def main():
    print(f'Waiting for /plan on this DDS bus ...')
    plan = wait_for_plan()
    print(f'Got plan with {len(plan.poses)} poses '
          f'(arclength {sum(np.linalg.norm(np.diff(np.array([[p.pose.position.x, p.pose.position.y] for p in plan.poses]), axis=0), axis=1)):.2f} m)')

    pts = sample_points(plan)
    print('Picked obstacle positions:')
    for name, (x, y) in zip(NAMES, pts):
        print(f'  {name}:  ({x:6.3f}, {y:6.3f})')

    write_yaml(pts)
    write_sdf(pts)

    print()
    print('Done. Now rebuild + restart Gazebo:')
    print('  colcon build --packages-select ammr_bringup')
    print('  source install/setup.bash')
    print("  pkill -9 -f 'gz sim'; pkill -9 -f gazebo")
    print('  ros2 launch ammr_bringup gazebo_dynamic.launch.py dynamic:=false')


if __name__ == '__main__':
    main()
